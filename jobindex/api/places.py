"""Where the open jobs are, as map points: ``GET /places.json`` (home-page globe).

Postings carry normalised place *names* (``city``, ``region``, ``country``), not
coordinates. They are placed with an offline gazetteer, ``jobindex/data/cities.tsv.gz``
(GeoNames cities with 15,000+ inhabitants, CC BY 4.0, regenerated by
``scripts/make_cities.py``): a city name is matched within its country, the region
breaks ties ("Portland, OR" vs "Portland, ME"), otherwise the most populous city wins;
failing a full match, the longest leading words that name a city are used
("Bengaluru Millenia", "Brighton and Hove").
Names that match nothing are left off the map (they still count everywhere else).

Counts are openings (deduplicated across sources), summed over the spellings that land
on the same city ("London", "LONDON"). The response is cached like ``/pulse``.
"""

import gzip
import time
import unicodedata
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
from typing import Any

import pycountry
from fastapi import APIRouter
from fastapi.responses import JSONResponse
from sqlalchemy import func, select
from sqlalchemy.ext.asyncio import AsyncSession

from jobindex.api.browse import search_url
from jobindex.api.deps import SessionDep
from jobindex.api.pulse import CACHE_SECONDS, country_name
from jobindex.api.search import group_id
from jobindex.models import Job, JobStatus

GAZETTEER = Path(__file__).resolve().parent.parent / "data" / "cities.tsv.gz"
TOP_PLACES = 150
MAX_NAME_ROWS = 5000  # distinct (city, region, country) spellings looked up per refresh


def place_key(name: str) -> str:
    """Comparable form of a place name: no accents, case or punctuation."""
    decomposed = unicodedata.normalize("NFKD", name)
    plain = "".join(c for c in decomposed if not unicodedata.combining(c)).casefold()
    return " ".join("".join(c if c.isalnum() else " " for c in plain).split())


def city_part(raw: str) -> str:
    """The city in a messy city field: "Kyiv | Київ" → "Kyiv", "Cairo - ETIC" → "Cairo"."""
    for sep in ("|", " - ", "/", "(", ","):
        raw = raw.split(sep)[0]
    return raw.strip()


@dataclass(frozen=True, slots=True)
class City:
    name: str
    country: str
    admin1: str
    lat: float
    lng: float
    population: int


@lru_cache(maxsize=1)
def gazetteer() -> dict[tuple[str, str], list[City]]:
    """(country, place_key) → cities, most populous first."""
    index: dict[tuple[str, str], list[City]] = {}
    with gzip.open(GAZETTEER, "rt", encoding="utf-8") as f:
        for line in f:
            if line.startswith("#"):
                continue
            cc, admin1, lat, lng, pop, name, keys = line.rstrip("\n").split("\t")
            city = City(name, cc, admin1, float(lat), float(lng), int(pop))
            for key in keys.split("|"):
                variants = {key}
                if key.endswith(" city"):  # "Makati City" is also "Makati"
                    variants.add(key.removesuffix(" city"))
                for k in variants:
                    index.setdefault((cc, k), []).append(city)
    for cities in index.values():  # file order is by population, keep it
        cities.sort(key=lambda c: -c.population)
    return index


@lru_cache(maxsize=4096)
def locate(city: str | None, region: str | None, country: str | None) -> City | None:
    """The gazetteer city for normalised location fields, or ``None``."""
    if not city or not country or len(country) != 2:
        return None
    cc = country.upper()
    key = place_key(city_part(city))
    if region and key in _country_keys(cc):
        key = place_key(city_part(region))  # "Israel" / "Tel Aviv": the city is in region
        region = None
    index = gazetteer()
    candidates = index.get((cc, key))
    words = key.split()
    while not candidates and len(words) > 1:  # "bengaluru millenia" -> "bengaluru"
        words.pop()
        prefix = " ".join(words)
        if len(prefix) >= 4:
            candidates = index.get((cc, prefix))
    if not candidates:
        return None
    if region:
        wanted = place_key(region)
        for candidate in candidates:
            if place_key(candidate.admin1) == wanted:
                return candidate
    return candidates[0]


def link_parts(city_name: str, region: str | None, city: City) -> tuple[str, str | None]:
    """City and region for a search link that finds these postings. The search's
    location filter compares whole fields and splits on commas, so the raw field is
    used unless it contains a comma; the region only when it is the city's admin1 code
    ("Portland, OR" vs "Portland, ME")."""

    def field(raw: str) -> str:
        return raw.strip() if "," not in raw else city_part(raw)

    if region and place_key(city_part(city_name)) in _country_keys(city.country):
        return field(region), None  # "Israel" / "Tel Aviv"
    same = region and place_key(region) == place_key(city.admin1)
    return field(city_name), region.strip() if same and region else None


def _country_keys(cc: str) -> set[str]:
    return {place_key(country_name(cc)), cc.lower()}


@lru_cache(maxsize=512)
def iso_numeric(code: str) -> str | None:
    """ISO 3166-1 numeric code ("840" for "US"), the feature id in world-atlas maps."""
    country = pycountry.countries.get(alpha_2=code)
    return str(country.numeric) if country is not None else None


@dataclass(slots=True)
class _Point:
    city: City
    count: int = 0
    best_spelling: str = ""
    best_region: str | None = None  # kept when it is the city's admin1 code ("OR")
    best_count: int = 0


async def compute_places(session: AsyncSession) -> dict[str, Any]:
    openings = func.count(func.distinct(group_id()))
    is_open = Job.status == JobStatus.OPEN
    rows = await session.execute(
        select(Job.city, Job.region, Job.country, openings)
        .where(is_open, Job.city.is_not(None), Job.city != "", Job.country.is_not(None))
        .group_by(Job.city, Job.region, Job.country)
        .order_by(openings.desc())
        .limit(MAX_NAME_ROWS)
    )
    points: dict[City, _Point] = {}
    for city_name, region, country, n in rows:
        city = locate(city_name, region, country)
        if city is None:
            continue
        point = points.setdefault(city, _Point(city))
        point.count += n
        if n > point.best_count:  # the link searches the most common spelling
            point.best_count = n
            point.best_spelling, point.best_region = link_parts(city_name, region, city)

    by_country = await session.execute(
        select(Job.country, openings)
        .where(is_open, Job.country.is_not(None))
        .group_by(Job.country)
        .order_by(openings.desc())
    )
    countries: dict[str, dict[str, Any]] = {}
    for code, n in by_country:
        numeric = iso_numeric(code) if len(code) == 2 else None
        if numeric:
            countries[numeric] = {
                "code": code,
                "name": country_name(code),
                "count": n,
                "href": f"/browse/{code}",
            }

    top = sorted(points.values(), key=lambda p: (-p.count, p.city.name))[:TOP_PLACES]
    return {
        "places": [
            {
                "name": p.city.name,
                "country": p.city.country,
                "country_name": country_name(p.city.country),
                "lat": p.city.lat,
                "lng": p.city.lng,
                "count": p.count,
                "href": search_url(p.best_spelling, p.best_region, p.city.country),
            }
            for p in top
        ],
        "countries": countries,
        "attribution": "City coordinates: GeoNames (CC BY 4.0)",
    }


_cache: dict[str, tuple[float, dict[str, Any]]] = {}


async def cached_places(session: AsyncSession) -> dict[str, Any]:
    hit = _cache.get("places")
    if hit and time.monotonic() - hit[0] < CACHE_SECONDS:
        return hit[1]
    data = await compute_places(session)
    _cache["places"] = (time.monotonic(), data)
    return data


router = APIRouter(include_in_schema=False)


@router.get("/places.json")
async def places_json(session: SessionDep) -> JSONResponse:
    """Top cities with open jobs (name, country, lat/lng, openings, search link) and
    openings per country keyed by ISO numeric code, for the home-page globe."""
    return JSONResponse(
        await cached_places(session),
        headers={
            "Cache-Control": f"public, max-age=300, s-maxage={CACHE_SECONDS}, "
            f"stale-while-revalidate={CACHE_SECONDS}"
        },
    )

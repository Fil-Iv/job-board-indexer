_LATAM = "AR BO BR BZ CL CO CR CU DO EC GT GY HN HT JM MX NI PA PE PR PY SR SV TT UY VE"
_NORTH_AMERICA = "CA US"


@dataclass(frozen=True, slots=True)
class Area:
    code: str  # value of Job.area
    label: str  # "Remote – Europe"
    search: str  # location search term that finds the area's postings
    countries: frozenset[str]  # ISO alpha-2 members highlighted on the map (empty: none)


def _codes(*groups: str) -> frozenset[str]:
    return frozenset(code for group in groups for code in group.split())


#: In the order they are matched (first wins) — see AREA_SQL in jobindex/models/job.py.
AREAS: tuple[Area, ...] = (
    Area("emea", "Remote – EMEA", "EMEA", _codes(_EUROPE, _MIDDLE_EAST, _AFRICA)),
    Area("europe", "Remote – Europe", "Europe", _codes(_EUROPE)),
    Area("apac", "Remote – Asia-Pacific", "APAC", _codes(_APAC)),
    Area("latam", "Remote – Latin America", "LATAM", _codes(_LATAM)),
    Area("americas", "Remote – Americas", "Americas", _codes(_NORTH_AMERICA, _LATAM)),
    Area("worldwide", "Remote – Worldwide", "Worldwide", frozenset()),
)
AREAS_BY_CODE = {a.code: a for a in AREAS}
AREAS_BY_SEARCH = {a.search.lower(): a for a in AREAS}

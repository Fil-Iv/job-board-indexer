"""Places without a database: the offline city gazetteer and the world regions.

* :func:`gazetteer` — ``jobindex/data/cities.tsv.gz`` (GeoNames cities with 15,000+
  inhabitants, CC BY 4.0, regenerated by ``scripts/make_cities.py``), indexed by
  (country, :func:`place_key`).
* :func:`country_of_city` — the country of a bare, unambiguous big-city name ("Sofia" →
  BG, "Warsaw" → PL); used by :mod:`jobindex.normalize` when a posting names a city but
  no country.
* :data:`AREAS` — world regions that region-only postings ("Remote - EMEA", "Europe")
  are filed under (``Job.area``, see ``jobindex/models/job.py``): label for ``/browse``
  and the map, and the member countries the map highlights.
"""

import gzip
import unicodedata
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

GAZETTEER = Path(__file__).resolve().parent / "data" / "cities.tsv.gz"

#: A bare city name gets a country only if its biggest namesake has this many
#: inhabitants and is this many times bigger than the next one in another country:
#: "Sofia" (1.2 M, BG), "London" (8.9 M vs 0.4 M in Canada) qualify; "Valencia" (VE 1.4 M
#: vs ES 0.8 M), "Cambridge" (GB vs US, both small) do not.
CITY_MIN_POPULATION = 200_000
CITY_DOMINANCE = 5


def place_key(name: str) -> str:
    """Comparable form of a place name: no accents, case or punctuation."""
    decomposed = unicodedata.normalize("NFKD", name)
    plain = "".join(c for c in decomposed if not unicodedata.combining(c)).casefold()
    return " ".join("".join(c if c.isalnum() else " " for c in plain).split())


def city_part(raw: str) -> str:
    """The city in a messy city field: "Kyiv | Київ" → "Kyiv", "Cairo - ETIC" → "Cairo"."""
    for sep in ("|", " - ", "/", "(", ","):
        raw = raw.split(sep)[0]
    return raw.strip()


@dataclass(frozen=True, slots=True)
class City:
    name: str
    country: str
    admin1: str
    lat: float
    lng: float
    population: int


def _read() -> list[tuple[City, list[str]]]:
    rows = []
    with gzip.open(GAZETTEER, "rt", encoding="utf-8") as f:
        for line in f:
            if line.startswith("#"):
                continue
            cc, admin1, lat, lng, pop, name, keys = line.rstrip("\n").split("\t")
            rows.append((City(name, cc, admin1, float(lat), float(lng), int(pop)), keys.split("|")))
    return rows


@lru_cache(maxsize=1)
def gazetteer() -> dict[tuple[str, str], list[City]]:
    """(country, place_key) → cities, most populous first."""
    index: dict[tuple[str, str], list[City]] = {}
    for city, keys in _read():
        for key in keys:
            variants = {key}
            if key.endswith(" city"):  # "Makati City" is also "Makati"
                variants.add(key.removesuffix(" city"))
            for k in variants:
                index.setdefault((city.country, k), []).append(city)
    for cities in index.values():  # file order is by population, keep it
        cities.sort(key=lambda c: -c.population)
    return index


@lru_cache(maxsize=1)
def _world_index() -> dict[str, list[tuple[City, bool]]]:
    """place_key → (city, matched by its own name rather than an alternate name)."""
    index: dict[str, list[tuple[City, bool]]] = {}
    for city, keys in _read():
        own = set(keys[:2])  # the GeoNames name and its ASCII form come first
        for key in keys:
            index.setdefault(key, []).append((city, key in own))
    for matches in index.values():
        matches.sort(key=lambda m: -m[0].population)
    return index


@lru_cache(maxsize=4096)
def country_of_city(name: str) -> str | None:
    """ISO country of a bare city name when one big city clearly owns the name, else
    ``None`` (conservative: ambiguous or small names stay without a country)."""
    matches = _world_index().get(place_key(city_part(name)))
    if not matches:
        return None
    best, own = matches[0]
    if not own or best.population < CITY_MIN_POPULATION:
        return None
    rival = next((c for c, _ in matches[1:] if c.country != best.country), None)
    if rival is not None and best.population < CITY_DOMINANCE * rival.population:
        return None
    return best.country



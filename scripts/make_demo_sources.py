"""Write coverage/demo_sources.yaml: 1-2 small example boards per done platform.

The hosted demo runs on the Supabase free tier (500 MB, docs/OPERATIONS.md#size-budget),
so it skips the huge example boards (e.g. 14k Marriott, 7k JPMorgan postings). Picks,
per ``done`` platform in coverage/platforms.yaml, the examples whose last coverage run
(coverage/results.json) succeeded, preferring boards with SMALL_MIN..SMALL_MAX open jobs
(smallest first); a platform without such a board gets only its smallest one.

    docker compose run --rm app python scripts/make_demo_sources.py [--check]

``--check`` exits 1 if the file is out of date instead of writing it.
"""

import argparse
import sys
from pathlib import Path

import yaml

from jobindex.coverage import PLATFORMS_FILE, ROOT, Results, load_platforms

OUT = ROOT / "coverage" / "demo_sources.yaml"
PER_PLATFORM = 2
SMALL_MIN, SMALL_MAX = 5, 400

HEADER = """\
# Boards of the hosted demo (docs/DEPLOY.md), registered with
#     python -m jobindex.cli seed-demo --file coverage/demo_sources.yaml
#
# GENERATED by scripts/make_demo_sources.py from coverage/platforms.yaml and
# coverage/results.json: 1-2 boards per done platform, preferring small ones so the
# database stays far below the Supabase free tier's 500 MB. Edit by hand if you like
# (re-running the script overwrites it). `jobs` = open postings at the last coverage run.
"""


def _jobs(item: tuple[str, int]) -> int:
    return item[1]


def build() -> str:
    results = Results.load()
    entries: list[dict[str, object]] = []
    for platform in load_platforms(PLATFORMS_FILE):
        if platform.status != "done":
            continue
        companies = dict(platform.example_companies)
        ok = []
        for url in platform.examples:
            result = results.examples.get(url)
            if result is not None and result.last_success_jobs:
                ok.append((url, result.last_success_jobs))

        small = sorted((item for item in ok if SMALL_MIN <= item[1] <= SMALL_MAX), key=_jobs)
        # No small board: only the smallest one (MAX_JOBS_PER_SOURCE caps what is stored).
        picks = small[:PER_PLATFORM] or sorted(ok, key=_jobs)[:1]
        for url, jobs in picks:
            entry: dict[str, object] = {"platform": platform.key, "url": url}
            if url in companies:
                entry["company"] = companies[url]
            entry["jobs"] = jobs
            entries.append(entry)
    body = yaml.safe_dump({"sources": entries}, sort_keys=False, allow_unicode=True, width=200)
    return HEADER + "\n" + body


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the file is stale")
    args = parser.parse_args()
    content = build()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != content:
            print(f"{OUT.relative_to(ROOT)} is out of date", file=sys.stderr)
            return 1
        return 0
    Path(OUT).write_text(content, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({content.count('- platform:')} sources)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
